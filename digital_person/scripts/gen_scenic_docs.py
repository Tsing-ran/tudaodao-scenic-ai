"""
生成新增景区的知识库文档（游览指南 + 结构化数据集），格式对齐示范景区公开资料包
（西湖/黄山/故宫扩展版的版式：纯叙述指南 + 单张 11 列结构化表）。
内容为真实公开事实，便于 RAG 入库后做准确率测试。
"""
from pathlib import Path
from docx import Document

OUT = Path(__file__).resolve().parent.parent / "示范景区公开资料包"

COLUMNS = ["景区名称", "景点ID", "景点名称", "具体位置", "建筑/景观参数",
           "文化内涵/历史背景", "游玩亮点/推荐活动", "适合人群",
           "游玩时长建议", "最佳游览时间", "注意事项"]


def build_guide(path: Path, title, intro, history, culture, spots, routes, practical):
    d = Document()
    d.add_heading(title, level=0)
    d.add_heading("景区简介", level=1); d.add_paragraph(intro)
    d.add_heading("历史沿革", level=1); d.add_paragraph(history)
    d.add_heading("文化意义", level=1); d.add_paragraph(culture)
    d.add_heading("主要景点介绍", level=1)
    for s in spots:
        d.add_heading(f"{s['name']}（{s['id']}）", level=2)
        desc = (f"{s['name']}位于{s['loc']}{s['param']}{s['culture']}"
                f"游玩亮点：{s['highlight']}建议游玩时长约{s['duration']}，"
                f"最佳游览时间为{s['best']}，较适合{s['fit']}。温馨提示：{s['note']}")
        d.add_paragraph(desc)
    d.add_heading("个性化游览路线推荐", level=1)
    for r in routes:
        d.add_heading(r["title"], level=2)
        d.add_paragraph(r["body"])
    d.add_heading("实用信息", level=1); d.add_paragraph(practical)
    d.save(str(path))
    print("写出指南:", path.name)


def build_dataset(path, scenic_title, scenic_name, spots):
    d = Document()
    d.add_heading(f"{scenic_title} 景点结构化数据集", level=0)
    t = d.add_table(rows=1, cols=len(COLUMNS))
    t.style = "Table Grid"
    for i, c in enumerate(COLUMNS):
        t.rows[0].cells[i].text = c
    for s in spots:
        row = t.add_row().cells
        vals = [scenic_name, s["id"], s["name"], s["loc"], s["param"], s["culture"],
                s["highlight"], s["fit"], s["duration"], s["best"], s["note"]]
        for i, v in enumerate(vals):
            row[i].text = v
    d.save(str(path))
    print("写出数据集:", path.name)


