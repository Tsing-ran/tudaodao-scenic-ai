def heading(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    return p


def body(doc, text):
    p = doc.add_paragraph(text)
    p.paragraph_format.space_after = Pt(6)
    return p


def generate_guide_doc(data: dict, out_dir: Path) -> Path:
    """生成综合导览文档。"""
    doc = Document()
    doc.add_heading(f"{data['full_name']}：历史、文化、景点特色与个性化游览指南", 0)

    heading(doc, "景区简介", 1)
    body(doc, data["intro"])

    heading(doc, "历史沿革", 1)
    body(doc, data["history"])

    heading(doc, "文化意义", 1)
    body(doc, data["culture"])

    heading(doc, "主要景点介绍", 1)
    for spot in data["spots"]:
        heading(doc, f"{spot['name']}（{spot['id']}）", 2)
        body(doc, f"位置：{spot['location']}")
        body(doc, f"规模参数：{spot['parameters']}")
        body(doc, f"文化内涵：{spot['culture']}")
        body(doc, f"游玩亮点：{spot['highlights']}")
        body(doc, f"适合人群：{spot['audience']} | 建议游览时长：{spot['duration']} | 最佳时间：{spot['best_time']}")
        body(doc, f"温馨提示：{spot['tips']}")

    heading(doc, "个性化游览路线推荐", 1)
    for route in data["routes"]:
        heading(doc, f"{route['name']}（{route['audience']}）", 2)
        body(doc, f"建议时长：{route['duration']}")
        body(doc, f"推荐顺序：{'→'.join(route['spots'])}")
        body(doc, route["desc"])

    heading(doc, "实用信息", 1)
    p = data["practical"]
    body(doc, f"开放时间：{p['hours']}")
    body(doc, f"门票价格：{p['ticket']}")
    body(doc, f"最佳游览季节：{p['best_season']}")
    body(doc, f"交通方式：{p['transport']}")

    filename = f"{data['full_name']}：历史、文化、景点特色与个性化游览指南.docx"
    path = out_dir / filename
    doc.save(path)
    return path


def generate_structured_doc(data: dict, out_dir: Path) -> Path:
    """生成景点结构化数据集（表格）。"""
    doc = Document()
    doc.add_heading(f"{data['full_name']} 景点结构化数据集", 0)
    body(doc, f"景区：{data['full_name']} | 导游角色：{data['guide_name']} | 景点数量：{len(data['spots'])}")

    headers = ["景区名称", "景点ID", "景点名称", "具体位置",
               "建筑/景观参数", "文化内涵/历史背景",
               "游玩亮点/推荐活动", "适合人群", "游玩时长建议",
               "最佳游览时间", "注意事项"]

    table = doc.add_table(rows=1 + len(data["spots"]), cols=len(headers))
    table.style = "Table Grid"

    # 表头
    for i, h in enumerate(headers):
        table.rows[0].cells[i].text = h

    # 数据行
    for ri, spot in enumerate(data["spots"]):
        row = table.rows[ri + 1]
        values = [
            data["name"], spot["id"], spot["name"], spot["location"],
            spot["parameters"], spot["culture"],
            spot["highlights"], spot["audience"], spot["duration"],
            spot["best_time"], spot["tips"],
        ]
        for ci, val in enumerate(values):
            row.cells[ci].text = val

    filename = f"{data['full_name']} 景点结构化数据集.docx"
    path = out_dir / filename
    doc.save(path)
    return path


